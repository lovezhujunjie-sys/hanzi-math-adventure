// sw.js —— 离线缓存：让「汉字·数学 大冒险」第二次打开不用等网络
//
// 🔴 为什么需要它：
//    这是给两个小孩用的 App——麟轩做作业、曾强在车上闹着要玩，这些时候
//    网速都不由我们说了算。缓存下来就永远不受网络摆布。
//
// 🔴 为什么选 stale-while-revalidate（缓存先给、后台悄悄更新）：
//    网络优先等于每次都要等首字节，白装。SWR 的代价是「改版后第一次打开
//    可能还是旧版、再打开一次才是新版」——这个 App 自用、改版不频繁，
//    用一次延迟换每次秒开，划算。
//    ⚠️ 所以我改完版如果孩子说「没看到新东西」，下拉刷新一次即可。
//
// 🔴 整个 App 只有一个文件：index.html 里**零外部引用**（无 <link>、无 CDN 外链），
//    所以缓存清单就一条，不存在「缓存了 HTML 却没缓存 CSS」那种半吊子状态。
//
// 🔴 每次改 index.html 都要顶下面的 VERSION：不顶的话老缓存不会被清，
//    SWR 又只保证「再打开一次才更新」，孩子会一直看到旧版。
//    2026-09-18 v1：首次上线——数学 11 关现场出题（含有余数除法）+ 汉字
//                   二年级 1078 字按册/单元/写字表·识字表分组 + 描红写字。
//    2026-09-18 v2：修量词——「几个图书」应为「几本图书」（图书论本、铅笔论支、
//                   糖果/弹珠/草莓论颗、贴纸论张、饼干论块、本子论本），
//                   并加了一道通用断言防止再错；顺带清掉题干小字里藏的「他」。
//    2026-09-18 v3：修三处「孩子根本没法答」的题（都是靠人肉看图才发现的，
//                   单元测试全绿也照样漏）——①「比多少」左右两边东西压根没画出来
//                   （数据放进了一个没人渲染的字段）②限时口算题面写着要看小棒、
//                   小棒却没画（改成直接出算式）③「列竖式」一屏装不下、确定键在屏幕外。
//    2026-09-18 v4：修「悬空量词」——量词后面没跟物品名时写死成「个」的两处
//                   （二宝减法小字「划掉 3 个 ❌」、应用题「送走 25 个 ➖」，
//                   草莓该论颗、铅笔该论支）；顺带把应用题「画不下画一截」的数量标注
//                   从行内改成另起一行——12 个 emoji 把一行撑满后，那个标注被挤得
//                   从中间断开（「…共 36」一行、光秃秃一个「颗」又一行）。
//                   断言同步扩容：新增「悬空量词」判据，已用放回 bug 的方式验证会叫。
//    2026-09-18 v5：比大小的讲解说清楚比的是哪一位——原文「位数一样，就从高位比起：
//                   5 和 3，5 大，所以 592 大」，「5 和 3」是哪儿的数，8 岁孩子得自己回头找；
//                   现在写成「百位上 5 比 3 大，所以 592 比 374 大」。前面几位打平时
//                   另起说法（「前面几位都一样，再看个位上…」），不会出现「从最高位比起」
//                   却跳到个位的别扭句。
//    2026-09-18 v6：生字表换成 **2025 年秋修订版**（原来用的是 2017 版）。字数从
//                   上 250/316、下 250/337 变成 上 250/460、下 250/449——
//                   旧数据的识字表本来就缺了两百多字，不换等于漏教。
//                   写字表把「语文园地」的字也计入（两册各 +20），新版上册写字表拼音
//                   是课本原样；下册课本电子版缺拼音层，是照词语表反推的（风险已记档）。
//    2026-09-18 v12：补三个「做完却没有任何回执」的缺口——描红写完没反应（现在盖章+计数+每 5 字 1 星）、
//                   错题本只能看不能练（现在每道题带凭据 _src，照着重出）、汉字成绩进不了报告（_key 一直是空的）。
//                   另加「答错后揭示条」：看拼音选字时选项里的字读不出来，答错后摊开这几个字的读音。
//    2026-09-18 v9：融合版上线——把 Claude Code + DeepSeek v4.1flash 那版的**全部功能与数据**
//                   （9 个屏 / 二年级 1100+ 字库 / 描红 / 拼音点读 / 45 句乘法口诀 /
//                   小棒·十格阵·点阵教具 / 关卡地图 / 限时口算 / 错题本 / 家长报告）植入进来，
//                   只重写视觉层换成糖果色 UI（珊瑚橙渐变按钮 #FF7A59→#FFB03A、淡蓝天空光晕背景
//                   #F3F7FF、果冻卡片、漂浮/摇摆动画）。顺带修一处 UI 语义：答错按钮原来用粉红
//                   （--grad-pink），改回红色（--grad-red #FF5C7A）——「错=红」是孩子的通用信号，
//                   也和 .feedback.no 的红底一致，粉红读起来像「可爱/中性」而非「答错」。
//    2026-09-18 v10：修一个「一打开就吓一跳」的 bug——手机/iPad/微信里点链接打开本页时，浏览器
//                   会在加载完成后于原触摸坐标补发一个 click（ghost click），点字注音把它当成真
//                   点击，就凭空弹出一个字的拼音气泡还朗读出来（老曾看到的是「星」字）。修法：注音
//                   只认「本页 pointerdown → click」成对的事件，残留点击没有配套按下一律忽略；正常
//                   点字注音不受影响。已用「放回 bug → 断言叫」验证过（t-py.js 的 ghost 断言）。
const VERSION = 'hm-2026-09-20.7';const INDEX = new URL('./index.html', self.location.href).href;

self.addEventListener('install', e => {
  e.waitUntil(
    caches.open(VERSION)
      .then(c => c.addAll([INDEX]))
      .catch(() => {})            // 首次预缓存失败不能把 SW 卡死在 installing
      .then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', e => {
  e.waitUntil(
    caches.keys()
      .then(ks => Promise.all(ks.filter(k => k !== VERSION).map(k => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', e => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;   // 不是自己的资源一律不碰

  // 🔴 导航请求必须映射到 INDEX 这个 key，不能直接 caches.match(req)：
  //    打开页面时请求的是仓库目录形式（…/hanzi-math-adventure/），
  //    而缓存里存的 key 是 …/index.html —— 两者 URL 不同，
  //    直接 match 会永远落空，缓存形同虚设（这是 SW 最常见的坑）。
  const key = req.mode === 'navigate' ? INDEX : req.url;

  e.respondWith((async () => {
    const cache = await caches.open(VERSION);
    const cached = await cache.match(key);
    // 后台更新：故意不 await，让它自己慢慢跑；失败也不影响这次返回什么
    const net = fetch(req).then(res => {
      if (res && res.status === 200 && res.type === 'basic') {
        cache.put(key, res.clone()).catch(() => {});
      }
      return res;
    }).catch(() => null);
    // 有缓存立刻给（这就是秒开的来源）；没有才等网络
    return cached || (await net) || new Response('离线，且本地没有缓存', {
      status: 503, headers: { 'Content-Type': 'text/plain; charset=utf-8' }
    });
  })());
});
